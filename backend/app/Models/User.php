<?php

namespace App\Models;

use Illuminate\Foundation\Auth\User as Authenticatable;
use Laravel\Sanctum\HasApiTokens;

class User extends Authenticatable
{
    use HasApiTokens;

    const ROLE_ADMINISTRATOR = 'Administrator';
    const ROLE_STORE_ADMIN = 'Store Administrator';
    const ROLE_EMPLOYEE = 'Employee';
    const ROLE_CUSTOMER = 'Customer';

    const POSITION_CASHIER = 'Cashier (Employee)';
    const POSITION_COLLECTOR = 'Collector (Employee)';
    const POSITION_UTILITY = 'Utility (Employee)';

    protected $table = 'users';

    protected $primaryKey = 'user_id';

    public $incrementing = true;

    protected $keyType = 'int';

    protected $fillable = [
        'employee_id',
        'customer_id',
        'username',
        'email',
        'phone_number',
        'password_hash',
        'role',
        'is_active',
        'account_verified',
        'account_verified_at',
        'account_verified_by',
        'last_login',
        'otp_code',
        'otp_expires_at',
        'otp_created_at',
        'profile_image',
        'face_biometric_image',
        'user_id',
    ];

    protected $hidden = [
        'password_hash',
        'otp_code',
    ];

    protected $casts = [
        'is_active' => 'boolean',
        'account_verified' => 'boolean',
        'account_verified_at' => 'datetime',
        'last_login' => 'datetime',
        'otp_expires_at' => 'datetime',
        'otp_created_at' => 'datetime',
    ];

    /**
     * Use username instead of email for authentication.
     */
    public function getAuthPasswordName()
    {
        return 'password_hash';
    }

    public function getAuthPassword()
    {
        return $this->password_hash;
    }

    /**
     * Relationship with employee.
     */
    public function employee()
    {
        return $this->belongsTo(
            Employee::class,
            'employee_id',
            'employee_id'
        );
    }

    /**
     * Relationship with customer.
     */
    public function customer()
    {
        return $this->belongsTo(
            Customer::class,
            'customer_id',
            'customer_id'
        );
    }

    /**
     * Administrator who verified the account.
     */
    public function verifiedBy()
    {
        return $this->belongsTo(
            User::class,
            'account_verified_by',
            'user_id'
        );
    }

    /**
     * Sales processed by this user.
     */
    public function processedSales()
    {
        return $this->hasMany(
            SaleTransaction::class,
            'processed_by',
            'user_id'
        );
    }

    public function qrRequests()
    {
        return $this->hasMany(
            QrRequest::class,
            'user_id',
            'user_id'
        );
    }

    /**
     * Branches managed by this Store Administrator.
     */
    public function managedBranches()
    {
        return $this->hasMany(BranchProfile::class, 'manager_id', 'user_id');
    }

    /**
     * Payments received/confirmed by this Store Admin or Cashier Employee.
     */
    public function receivedPayments()
    {
        return $this->hasMany(Payment::class, 'received_by', 'user_id');
    }

    /**
     * Payroll records generated by this Administrator or Store Admin.
     */
    public function generatedPayrolls()
    {
        return $this->hasMany(Payroll::class, 'generated_by', 'user_id');
    }

    /**
     * Payroll records approved by this Administrator or Store Admin.
     */
    public function approvedPayrolls()
    {
        return $this->hasMany(Payroll::class, 'approved_by', 'user_id');
    }

    /**
     * Payroll periods created by this Administrator or Store Admin.
     */
    public function createdPayrollPeriods()
    {
        return $this->hasMany(PayrollPeriod::class, 'created_by', 'user_id');
    }

    /**
     * Payslips belonging to this Employee / Store Admin user.
     */
    public function payslips()
    {
        return $this->hasMany(Payslip::class, 'employee_id', 'employee_id');
    }

    /**
     * Statements belonging to this Customer user.
     */
    public function statements()
    {
        return $this->hasMany(Statement::class, 'customer_id', 'customer_id');
    }

    /**
     * Attendance records scanned by this Store Admin.
     */
    public function scannedAttendances()
    {
        return $this->hasMany(Attendance::class, 'scanned_by', 'user_id');
    }

    /**
     * Attendance scan logs recorded by this Store Admin.
     */
    public function scannedLogs()
    {
        return $this->hasMany(AttendanceScanLog::class, 'scanned_by', 'user_id');
    }

    /**
     * Employee excuse/leave letters submitted by this user.
     */
    public function employeeLetters()
    {
        return $this->hasMany(EmployeeLetter::class, 'user_id', 'user_id');
    }

    /**
     * Employee excuse/leave letters reviewed by this Administrator or Store Admin.
     */
    public function reviewedLetters()
    {
        return $this->hasMany(EmployeeLetter::class, 'reviewed_by', 'user_id');
    }

    /**
     * Support messages responded to by this Administrator or Store Admin.
     */
    public function respondedSupportMessages()
    {
        return $this->hasMany(SupportMessage::class, 'responded_by', 'user_id');
    }

    /**
     * Weekly/branch reports created by this Store Admin.
     */
    public function createdReports()
    {
        return $this->hasMany(Report::class, 'created_by', 'user_id');
    }

    /**
     * Weekly/branch reports reviewed by this Administrator.
     */
    public function reviewedReports()
    {
        return $this->hasMany(Report::class, 'reviewed_by', 'user_id');
    }

    /**
     * E-Wallet deposits initiated by this Customer user.
     */
    public function ewalletDeposits()
    {
        return $this->hasMany(EWalletDeposit::class, 'user_id', 'user_id');
    }

    /**
     * Notifications addressed to this user across all modules.
     */
    public function notifications()
    {
        return $this->hasMany(Notification::class, 'user_id', 'user_id');
    }

    /**
     * System audit logs recorded for this user.
     */
    public function systemLogs()
    {
        return $this->hasMany(SystemLog::class, 'user_id', 'user_id');
    }

    /**
     * Database backup logs created by this Administrator.
     */
    public function backupLogs()
    {
        return $this->hasMany(BackupLog::class, 'created_by', 'user_id');
    }

    /**
     * Synchronize account active/inactive statuses based on live login sessions.
     * Logged-in accounts are automatically marked Active; logged-out accounts are marked Inactive.
     */
    public static function syncSessionStatuses(?User $currentUser = null): void
    {
        try {
            $now = now();

            // 1. Clean up never-used tokens (created > 5 mins ago) or expired tokens (idle > 2 hours)
            \Illuminate\Support\Facades\DB::table('personal_access_tokens')
                ->where('tokenable_type', self::class)
                ->where(function ($q) use ($now) {
                    $q->where(function ($sub) use ($now) {
                        $sub->whereNull('last_used_at')
                            ->where('created_at', '<', $now->copy()->subMinutes(5));
                    })->orWhere('last_used_at', '<', $now->copy()->subHours(2));
                })
                ->delete();

            // 2. Collect all user IDs with an active login session token
            $activeUserIds = \Illuminate\Support\Facades\DB::table('personal_access_tokens')
                ->where('tokenable_type', self::class)
                ->pluck('tokenable_id')
                ->map(fn($id) => (int) $id)
                ->unique()
                ->values()
                ->all();

            if ($currentUser && $currentUser->user_id) {
                $activeUserIds[] = (int) $currentUser->user_id;
                $activeUserIds = array_values(array_unique($activeUserIds));
            }

            // 3. Update users table (is_active = true when logged in, false when logged out)
            if (!empty($activeUserIds)) {
                self::whereIn('user_id', $activeUserIds)
                    ->where('is_active', false)
                    ->update(['is_active' => true]);

                self::whereNotIn('user_id', $activeUserIds)
                    ->where('is_active', true)
                    ->update(['is_active' => false]);
            } else {
                self::where('is_active', true)->update(['is_active' => false]);
            }

            // 4. Sync linked employees table status ('Active' when logged in, 'Inactive' when logged out)
            $activeEmpIds = !empty($activeUserIds)
                ? self::whereIn('user_id', $activeUserIds)
                    ->whereNotNull('employee_id')
                    ->pluck('employee_id')
                    ->map(fn($id) => (int) $id)
                    ->all()
                : [];

            if (!empty($activeEmpIds)) {
                Employee::whereIn('employee_id', $activeEmpIds)
                    ->where('status', '!=', 'Active')
                    ->update(['status' => 'Active']);

                Employee::whereNotIn('employee_id', $activeEmpIds)
                    ->where('status', '!=', 'Inactive')
                    ->update(['status' => 'Inactive']);
            } else {
                Employee::where('status', '!=', 'Inactive')->update(['status' => 'Inactive']);
            }

            // 5. Sync linked customers table status ('Active' when logged in, 'Inactive' when logged out)
            $activeCustIds = !empty($activeUserIds)
                ? self::whereIn('user_id', $activeUserIds)
                    ->whereNotNull('customer_id')
                    ->pluck('customer_id')
                    ->map(fn($id) => (int) $id)
                    ->all()
                : [];

            if (!empty($activeCustIds)) {
                Customer::whereIn('customer_id', $activeCustIds)
                    ->where('status', '!=', 'Active')
                    ->update(['status' => 'Active']);

                Customer::whereNotIn('customer_id', $activeCustIds)
                    ->where('status', '!=', 'Inactive')
                    ->update(['status' => 'Inactive']);
            } else {
                Customer::where('status', '!=', 'Inactive')->update(['status' => 'Inactive']);
            }
        } catch (\Throwable $e) {
            // Silently ignore during migrations or if tables are not ready
        }
    }
}
