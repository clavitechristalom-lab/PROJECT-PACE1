        $mail->setFrom($fromEmail, $fromName);
        $mail->addAddress($email, $recipientName);
        $mail->addReplyTo($fromEmail, $fromName);

        // Transactional Priority: Normal (3)
        $mail->Priority = 3;

        // Auto-Response suppression for transactional emails
        $mail->addCustomHeader('X-Auto-Response-Suppress', 'All');

        // NOTE: Strictly omit 'Precedence: bulk' - this triggers Spam / Promotions folder!
        // NOTE: Strictly omit forged '@zlicz.com' Message-ID; allow Google SMTP to generate authentic Message-ID passing SPF/DKIM/DMARC

        $subject = match($type) {
            'registration'   => '[PROJECT: PACE Z-LICZ] Complete your account verification',
            'password_reset' => '[PROJECT: PACE Z-LICZ] Password reset verification code',
