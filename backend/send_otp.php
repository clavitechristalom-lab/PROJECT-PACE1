    try {
        $stmtUser = $pdo->prepare("
            SELECT user_id, username, email, role, is_active, employee_id, customer_id
            FROM users 
            WHERE (LOWER(email) = LOWER(?) OR LOWER(username) = LOWER(?)) 
              AND (is_active = 1 OR is_active IS NULL)
            LIMIT 1
        ");
        $stmtUser->execute([$rawTarget, $rawTarget]);
        $uRow = $stmtUser->fetch(PDO::FETCH_ASSOC);

        if ($uRow) {
            $user = $uRow;
            $userId = (int) $uRow['user_id'];
            $resolvedEmail = !empty($uRow['email']) ? trim($uRow['email']) : null;
            $recipientName = $uRow['username'];

            // Linked customer record
            if (!empty($uRow['customer_id'])) {
                $stmtCust = $pdo->prepare("SELECT first_name, last_name, email FROM customers WHERE customer_id = ? LIMIT 1");
                $stmtCust->execute([$uRow['customer_id']]);
                $cRow = $stmtCust->fetch(PDO::FETCH_ASSOC);
                if ($cRow) {
                    if (!empty($cRow['first_name'])) {
                        $recipientName = trim($cRow['first_name'] . ' ' . ($cRow['last_name'] ?? ''));
                    }
                    if (empty($resolvedEmail) && !empty($cRow['email'])) {
                        $resolvedEmail = trim($cRow['email']);
                    }
                }
            }

            // Linked employee record
            if (!empty($uRow['employee_id'])) {
                $stmtEmp = $pdo->prepare("SELECT first_name, last_name, email FROM employees WHERE employee_id = ? LIMIT 1");
                $stmtEmp->execute([$uRow['employee_id']]);
                $eRow = $stmtEmp->fetch(PDO::FETCH_ASSOC);
                if ($eRow) {
                    if (!empty($eRow['first_name'])) {
                        $recipientName = trim($eRow['first_name'] . ' ' . ($eRow['last_name'] ?? ''));
                    }
                    if (empty($resolvedEmail) && !empty($eRow['email'])) {
                        $resolvedEmail = trim($eRow['email']);
                    }
                }
            }
        }
    } catch (\Throwable $e) {}

    // Check residents table if not resolved
    if (empty($resolvedEmail)) {
        try {
            $stmtRes = $pdo->prepare("SELECT id, firstName, lastName, email FROM residents WHERE LOWER(email) = LOWER(?) LIMIT 1");
            $stmtRes->execute([$rawTarget]);
            $rRow = $stmtRes->fetch(PDO::FETCH_ASSOC);
            if ($rRow && !empty($rRow['email'])) {
                $resolvedEmail = trim($rRow['email']);
                if (!empty($rRow['firstName'])) {
                    $recipientName = trim($rRow['firstName'] . ' ' . ($rRow['lastName'] ?? ''));
                }
            }
        } catch (\Throwable $e) {}
    }

    // Direct search in customers table if rawTarget is email
    if (empty($resolvedEmail)) {
        try {
            $stmtCustDirect = $pdo->prepare("SELECT customer_id, first_name, last_name, email FROM customers WHERE LOWER(email) = LOWER(?) LIMIT 1");
            $stmtCustDirect->execute([$rawTarget]);
            $cDirect = $stmtCustDirect->fetch(PDO::FETCH_ASSOC);
            if ($cDirect && !empty($cDirect['email'])) {
                $recipientName = trim($cDirect['first_name'] . ' ' . ($cDirect['last_name'] ?? ''));
                $resolvedEmail = trim($cDirect['email']);
            }
        } catch (\Throwable $e) {}
    }

    // Direct search in employees table if still not found
    if (empty($resolvedEmail)) {
        try {
            $stmtEmpDirect = $pdo->prepare("SELECT employee_id, first_name, last_name, email FROM employees WHERE LOWER(email) = LOWER(?) LIMIT 1");
            $stmtEmpDirect->execute([$rawTarget]);
            $eDirect = $stmtEmpDirect->fetch(PDO::FETCH_ASSOC);
            if ($eDirect && !empty($eDirect['email'])) {
                $recipientName = trim($eDirect['first_name'] . ' ' . ($eDirect['last_name'] ?? ''));
                $resolvedEmail = trim($eDirect['email']);
            }
        } catch (\Throwable $e) {}
    }

    // Fallback: If rawTarget is a valid email
    if (empty($resolvedEmail) && filter_var($rawTarget, FILTER_VALIDATE_EMAIL)) {
        $resolvedEmail = $rawTarget;
        if ($isRegistration) {
            $recipientName = trim($input['first_name'] ?? 'New Customer');
        }
    }

    if (empty($resolvedEmail) || !filter_var($resolvedEmail, FILTER_VALIDATE_EMAIL)) {
        http_response_code(422);
        echo json_encode([
            "success" => false,
            "message" => "A valid email address is required to receive verification code."
        ]);
        exit();
    }

    $clientIp = $_SERVER['REMOTE_ADDR'] ?? '127.0.0.1';
    $userAgent = $_SERVER['HTTP_USER_AGENT'] ?? null;

    // Rate Limiting Check: 30-second cooldown per email
    try {
        $stmtCooldown = $pdo->prepare("SELECT created_at FROM password_reset_otp WHERE LOWER(email) = LOWER(?) ORDER BY id DESC LIMIT 1");
        $stmtCooldown->execute([$resolvedEmail]);
        $lastOtp = $stmtCooldown->fetch(PDO::FETCH_ASSOC);
        if ($lastOtp && !empty($lastOtp['created_at'])) {
            $lastTime = strtotime($lastOtp['created_at']);
            $elapsed = time() - $lastTime;
            if ($elapsed < 30) {
                $rem = 30 - $elapsed;
                http_response_code(429);
                echo json_encode([
                    "success"           => false,
                    "message"           => "Please wait {$rem} seconds before requesting another verification code.",
                    "remaining_seconds" => $rem
                ]);
                exit();
            }
        }
    } catch (\Throwable $e) {}

    // Cryptographically generate true 6-digit numeric code
    $otp_code = sprintf("%06d", mt_rand(100000, 999999));
    $expiry_time = date("Y-m-d H:i:s", time() + (15 * 60));

    // Clear old active tokens and insert into password_reset_otp with DATE_ADD(NOW(), INTERVAL 15 MINUTE) and used = 0
    try {
        $stmtDelReset = $pdo->prepare("DELETE FROM password_reset_otp WHERE LOWER(email) = LOWER(?)");
        $stmtDelReset->execute([$resolvedEmail]);

        $stmtInsReset = $pdo->prepare("
            INSERT INTO password_reset_otp (email, otp_code, used, expiry_time, created_at, updated_at)
            VALUES (?, ?, 0, DATE_ADD(NOW(), INTERVAL 15 MINUTE), NOW(), NOW())
        ");
        $stmtInsReset->execute([$resolvedEmail, $otp_code]);
    } catch (\Throwable $e) {
        error_log("[DB OTP RESET ERROR] " . $e->getMessage());
    }

    // Multi-table compatibility: save into otps table
    try {
        $stmtClear = $pdo->prepare("UPDATE otps SET used = 1, updated_at = NOW() WHERE LOWER(email) = LOWER(?) AND used = 0");
        $stmtClear->execute([$resolvedEmail]);

        $stmtInsertOtp = $pdo->prepare("
            INSERT INTO otps (user_id, email, otp_code, type, used, expiry_time, ip_address, user_agent, created_at, updated_at)
            VALUES (?, ?, ?, ?, 0, DATE_ADD(NOW(), INTERVAL 15 MINUTE), ?, ?, NOW(), NOW())
        ");
        $stmtInsertOtp->execute([
            $userId,
            $resolvedEmail,
            $otp_code,
            $type,
            $clientIp,
            $userAgent
        ]);
    } catch (\Throwable $e) {}

    // Synchronize to users table if userId is present
    if ($userId) {
        try {
            $stmtSync = $pdo->prepare("UPDATE users SET otp_code = ?, otp_expires_at = DATE_ADD(NOW(), INTERVAL 15 MINUTE), otp_created_at = NOW() WHERE user_id = ?");
            $stmtSync->execute([$otp_code, $userId]);
        } catch (\Throwable $e) {}
    }

    // Dispatch live Gmail SMTP email via background CLI worker or direct fallback
    $phpBin = getPhpCliBinary();
    $scriptPath = __FILE__;
    if (str_starts_with(strtoupper(PHP_OS), 'WIN')) {
        $cmd = 'cmd /c start "" /B "' . str_replace('/', '\\', $phpBin) . '" "' . str_replace('/', '\\', $scriptPath) . '" ' . escapeshellarg($resolvedEmail) . ' ' . escapeshellarg($otp_code) . ' ' . escapeshellarg($recipientName) . ' ' . escapeshellarg($type) . ' > NUL 2>&1';
        @pclose(@popen($cmd, 'r'));
    } else {
        $cmd = escapeshellarg($phpBin) . ' ' . escapeshellarg($scriptPath) . ' ' . escapeshellarg($resolvedEmail) . ' ' . escapeshellarg($otp_code) . ' ' . escapeshellarg($recipientName) . ' ' . escapeshellarg($type) . ' > /dev/null 2>&1 &';
        @exec($cmd);
    }

    // Mask recipient email for privacy in response (e.g. z***z@gmail.com)
    $parts = explode('@', $resolvedEmail, 2);
    $masked = strlen($parts[0]) > 2
        ? substr($parts[0], 0, 1) . '***' . substr($parts[0], -1)
        : substr($parts[0], 0, 1) . '***';
    $maskedEmail = "{$masked}@{$parts[1]}";

    http_response_code(200);
    echo json_encode([
        "success"            => true,
        "message"            => "A 6-digit verification code has been dispatched to {$maskedEmail}.",
        "email"              => $resolvedEmail,
        "masked_email"       => $maskedEmail,
        "recipient_email"    => $maskedEmail,
        "masked_target"      => $maskedEmail,
        "expires_in_seconds" => 900,
        "cooldown_seconds"   => 30,
        "user_id"            => $userId
    ]);

} catch (Exception $e) {
    http_response_code(500);
    echo json_encode([
        "success" => false, 
        "message" => $e->getMessage()
    ]);
}
