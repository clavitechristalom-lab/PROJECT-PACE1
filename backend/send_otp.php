/**
 * Resolve valid PHP CLI executable, avoiding web server executables (such as httpd.exe under Apache mod_php).
 */
function getPhpCliBinary(): string {
    if (defined('PHP_BINARY') && PHP_BINARY && str_ends_with(strtolower(PHP_BINARY), 'php.exe') && file_exists(PHP_BINARY)) {
        return PHP_BINARY;
    }
    $candidates = [
        'C:\\xampp\\php\\php.exe',
        'C:\\php\\php.exe',
    ];
    foreach ($candidates as $bin) {
        if (file_exists($bin)) {
            return $bin;
        }
    }
    return 'php';
}

