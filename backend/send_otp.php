// CLI Background Dispatcher Entrypoint: php send_otp.php <test_email> <otp_code> <name> <type>
if (php_sapi_name() === 'cli' && !empty($argv[1])) {
    $cliEmail = $argv[1];
    $cliOtp   = $argv[2] ?? sprintf('%06d', mt_rand(100000, 999999));
    $cliName  = $argv[3] ?? 'Valued Customer';
    $cliType  = $argv[4] ?? 'login';

    $result = sendOTPEmail($cliEmail, $cliOtp, $cliName, $cliType);
    if ($result['success']) {
        echo "SUCCESS: OTP {$cliOtp} sent to {$cliEmail} via Port " . ($result['port'] ?? 587) . " [250 2.0.0 OK]\n";
        exit(0);
    } else {
        echo "FAILED: " . ($result['error_details'] ?? $result['message']) . "\n";
        exit(1);
    }
}

// HTTP API Headers
if (!headers_sent()) {
    header("Access-Control-Allow-Origin: *");
    header("Content-Type: application/json; charset=UTF-8");
    header("Access-Control-Allow-Methods: POST, OPTIONS");
    header("Access-Control-Allow-Headers: Content-Type, Authorization, X-Requested-With, Accept");
}

if (isset($_SERVER['REQUEST_METHOD']) && strtoupper($_SERVER['REQUEST_METHOD']) === 'OPTIONS') {
    http_response_code(200);
    exit();
}

try {
    $input = json_decode(file_get_contents('php://input'), true);
    if (empty($input)) {
        $input = $_POST;
    }

    $rawTarget = trim($input['user_email'] ?? ($input['email'] ?? ($input['target'] ?? ($input['username'] ?? ''))));
    $type = trim($input['type'] ?? 'login');
    $isRegistration = ($type === 'registration');

    if (empty($rawTarget)) {
        http_response_code(422);
        echo json_encode([
            "success" => false,
            "message" => "Email address or username is required."
        ]);
        exit();
    }

    $user = null;
    $recipientName = 'Valued Customer';
    $userId = null;
    $resolvedEmail = null;

